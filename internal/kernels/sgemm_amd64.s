	CMPQ R8, $0
	JLE  done
	VMOVUPS Z0, K1, (DI)
	VMOVUPS Z1, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $1
	JLE  done
	VMOVUPS Z2, K1, (DI)
	VMOVUPS Z3, K2, 64(DI)
