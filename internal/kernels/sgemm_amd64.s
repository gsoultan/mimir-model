// AVX-512 kernel for float32 matrix products (sgemm.go).

// func sgemm12x32(a, b *float32, ldb int, c *float32, ldc, k, rows int, mask uint32, acc int, bias *float32)
//
// C[r][j] = sum over kk of A[kk][r] * B[kk][j] for r < rows and the
// columns j < 32 whose bit is set in mask (the low 16 bits for the first
// 16 columns, the high 16 for the next 16), with each sum a chain of
// fused multiply-adds in the order of kk. A is packed as k rows of 12
// floats; row kk of B is at b + 4*kk*ldb bytes, row r of C at
// c + 4*r*ldc. With acc != 0 the chains start from the values in C
// instead of zero, so a product split along k gives the same result as
// one call. With bias != nil, bias[r] is added to row r at the end.
TEXT ·sgemm12x32(SB), NOSPLIT, $0-80
	MOVQ a+0(FP), AX
	MOVQ b+8(FP), SI
	MOVQ ldb+16(FP), BX
	SHLQ $2, BX
	MOVQ c+24(FP), DI
	MOVQ ldc+32(FP), DX
	SHLQ $2, DX
	MOVQ k+40(FP), CX
	MOVQ rows+48(FP), R8
	MOVL mask+56(FP), R9
	KMOVW R9, K1
	SHRL $16, R9
	KMOVW R9, K2
	MOVQ acc+64(FP), R10
	MOVQ bias+72(FP), R11

	VPXORD Z0, Z0, Z0
	VPXORD Z1, Z1, Z1
	VPXORD Z2, Z2, Z2
	VPXORD Z3, Z3, Z3
	VPXORD Z4, Z4, Z4
	VPXORD Z5, Z5, Z5
	VPXORD Z6, Z6, Z6
	VPXORD Z7, Z7, Z7
	VPXORD Z8, Z8, Z8
	VPXORD Z9, Z9, Z9
	VPXORD Z10, Z10, Z10
	VPXORD Z11, Z11, Z11
	VPXORD Z12, Z12, Z12
	VPXORD Z13, Z13, Z13
	VPXORD Z14, Z14, Z14
	VPXORD Z15, Z15, Z15
	VPXORD Z16, Z16, Z16
	VPXORD Z17, Z17, Z17
	VPXORD Z18, Z18, Z18
	VPXORD Z19, Z19, Z19
	VPXORD Z20, Z20, Z20
	VPXORD Z21, Z21, Z21
	VPXORD Z22, Z22, Z22
	VPXORD Z23, Z23, Z23
	TESTQ R10, R10
	JZ    loop
	MOVQ  DI, R12
	CMPQ R8, $0
	JLE  loop
	VMOVUPS.Z (R12), K1, Z0
	VMOVUPS.Z 64(R12), K2, Z1
	ADDQ DX, R12
	CMPQ R8, $1
	JLE  loop
	VMOVUPS.Z (R12), K1, Z2
	VMOVUPS.Z 64(R12), K2, Z3
	ADDQ DX, R12
	CMPQ R8, $2
	JLE  loop
	VMOVUPS.Z (R12), K1, Z4
	VMOVUPS.Z 64(R12), K2, Z5
	ADDQ DX, R12
	CMPQ R8, $3
	JLE  loop
	VMOVUPS.Z (R12), K1, Z6
	VMOVUPS.Z 64(R12), K2, Z7
	ADDQ DX, R12
	CMPQ R8, $4
	JLE  loop
	VMOVUPS.Z (R12), K1, Z8
	VMOVUPS.Z 64(R12), K2, Z9
	ADDQ DX, R12
	CMPQ R8, $5
	JLE  loop
	VMOVUPS.Z (R12), K1, Z10
	VMOVUPS.Z 64(R12), K2, Z11
	ADDQ DX, R12
	CMPQ R8, $6
	JLE  loop
	VMOVUPS.Z (R12), K1, Z12
	VMOVUPS.Z 64(R12), K2, Z13
	ADDQ DX, R12
	CMPQ R8, $7
	JLE  loop
	VMOVUPS.Z (R12), K1, Z14
	VMOVUPS.Z 64(R12), K2, Z15
	ADDQ DX, R12
	CMPQ R8, $8
	JLE  loop
	VMOVUPS.Z (R12), K1, Z16
	VMOVUPS.Z 64(R12), K2, Z17
	ADDQ DX, R12
	CMPQ R8, $9
	JLE  loop
	VMOVUPS.Z (R12), K1, Z18
	VMOVUPS.Z 64(R12), K2, Z19
	ADDQ DX, R12
	CMPQ R8, $10
	JLE  loop
	VMOVUPS.Z (R12), K1, Z20
	VMOVUPS.Z 64(R12), K2, Z21
	ADDQ DX, R12
	CMPQ R8, $11
	JLE  loop
	VMOVUPS.Z (R12), K1, Z22
	VMOVUPS.Z 64(R12), K2, Z23
	ADDQ DX, R12

loop:
	TESTQ CX, CX
	JZ    tail
	VMOVUPS.Z (SI), K1, Z24
	VMOVUPS.Z 64(SI), K2, Z25
	VFMADD231PS.BCST 0(AX), Z24, Z0
