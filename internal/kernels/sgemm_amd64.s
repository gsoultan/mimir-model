// func convGatherF32(x *float32, idx *int32, masks *uint16, chunks, k int, w *float32, ws, rows int, bias *float32, y *float32, plane, tail int)
//
// For chunk c of 16 output positions and filter f < rows: y[f*plane +
// c*16 + j] = bias[f] + the sum over the taps t < k of w[t*ws+f] *
// x[idx[(c*k+t)*16+j]], the sum accumulated by fused multiply-adds in
// the taps' order as sgemm12x32 does, and bias added last (none when
// nil). Lanes clear in masks[c*k+t] read 0 instead of x. The last chunk
// stores the lanes of tail. Generated by gen/convgather.py.
TEXT ·convGatherF32(SB), NOSPLIT, $0-96
	MOVQ x+0(FP), SI
	MOVQ idx+8(FP), DX
	MOVQ masks+16(FP), R9
	MOVQ chunks+24(FP), R12
	MOVQ k+32(FP), R13
	MOVQ w+40(FP), R14
	MOVQ ws+48(FP), R15
	SHLQ $2, R15
	MOVQ rows+56(FP), AX
	MOVQ bias+64(FP), R10
	MOVQ y+72(FP), DI
	MOVQ plane+80(FP), R11
	SHLQ $2, R11
	MOVQ tail+88(FP), BX

