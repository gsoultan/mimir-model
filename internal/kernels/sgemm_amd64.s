	VPXORD Z20, Z20, Z20
	VPXORD Z21, Z21, Z21
	VPXORD Z22, Z22, Z22
	VPXORD Z23, Z23, Z23
	TESTQ R10, R10
	JZ    loop
	MOVQ  DI, R12
	CMPQ R8, $0
	JLE  loop
	VEXPANDPS.Z (R12), K1, Z0
	VEXPANDPS.Z (R12)(R15*1), K2, Z1
	ADDQ DX, R12
	CMPQ R8, $1
	JLE  loop
