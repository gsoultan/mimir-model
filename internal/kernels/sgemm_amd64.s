	JZ    store
	VBROADCASTSS 0(R11), Z26
	VADDPS Z26, Z0, Z0
	VADDPS Z26, Z1, Z1
	VBROADCASTSS 4(R11), Z26
	VADDPS Z26, Z2, Z2
	VADDPS Z26, Z3, Z3
	VBROADCASTSS 8(R11), Z26
	VADDPS Z26, Z4, Z4
	VADDPS Z26, Z5, Z5
	VBROADCASTSS 12(R11), Z26
	VADDPS Z26, Z6, Z6
	VADDPS Z26, Z7, Z7
	VBROADCASTSS 16(R11), Z26
	VADDPS Z26, Z8, Z8
	VADDPS Z26, Z9, Z9
	VBROADCASTSS 20(R11), Z26
	VADDPS Z26, Z10, Z10
