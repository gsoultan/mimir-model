//go:build amd64 && !purego

#include "textflag.h"

// AVX-512 kernel for float32 matrix products (sgemm.go).

// func sgemm12x32(a, b *float32, ldb int, c *float32, ldc, k, rows int, mask uint32, acc int, bias *float32)
//
// C[r][j] = sum over kk of A[kk][r] * B[kk][j] for r < rows and the
// columns j < 32 whose bit is set in mask (the low 16 bits for the first
// 16 columns, the high 16 for the next 16), with each sum a chain of
// fused multiply-adds in the order of kk. A is packed as k rows of 12
// floats; row kk of B is at b + 4*kk*ldb bytes, row r of C at
// c + 4*r*ldc. With acc != 0 the chains start from the values in C
// instead of zero, so a product split along k gives the same result as
// one call. With bias != nil, bias[r] is added to row r at the end.
TEXT ·sgemm12x32(SB), NOSPLIT, $0-80
	MOVQ a+0(FP), AX
	MOVQ b+8(FP), SI
	MOVQ ldb+16(FP), BX
	SHLQ $2, BX
	MOVQ c+24(FP), DI
	MOVQ ldc+32(FP), DX
	SHLQ $2, DX
	MOVQ k+40(FP), CX
	MOVQ rows+48(FP), R8
	MOVL mask+56(FP), R9
	KMOVW R9, K1
	SHRL $16, R9
	KMOVW R9, K2
	MOVQ acc+64(FP), R10
	MOVQ bias+72(FP), R11

	VPXORD Z0, Z0, Z0
	VPXORD Z1, Z1, Z1
	VPXORD Z2, Z2, Z2
	VPXORD Z3, Z3, Z3
	VPXORD Z4, Z4, Z4
	VPXORD Z5, Z5, Z5
	VPXORD Z6, Z6, Z6
	VPXORD Z7, Z7, Z7
	VPXORD Z8, Z8, Z8
	VPXORD Z9, Z9, Z9
	VPXORD Z10, Z10, Z10
	VPXORD Z11, Z11, Z11
	VPXORD Z12, Z12, Z12
	VPXORD Z13, Z13, Z13
	VPXORD Z14, Z14, Z14
	VPXORD Z15, Z15, Z15
	VPXORD Z16, Z16, Z16
	VPXORD Z17, Z17, Z17
	VPXORD Z18, Z18, Z18
	VPXORD Z19, Z19, Z19
	VPXORD Z20, Z20, Z20
	VPXORD Z21, Z21, Z21
	VPXORD Z22, Z22, Z22
	VPXORD Z23, Z23, Z23
	TESTQ R10, R10
	JZ    loop
	MOVQ  DI, R12
	CMPQ R8, $0
	JLE  loop
	VMOVUPS.Z (R12), K1, Z0
	VMOVUPS.Z 64(R12), K2, Z1
	ADDQ DX, R12
	CMPQ R8, $1
	JLE  loop
	VMOVUPS.Z (R12), K1, Z2
	VMOVUPS.Z 64(R12), K2, Z3
	ADDQ DX, R12
	CMPQ R8, $2
	JLE  loop
	VMOVUPS.Z (R12), K1, Z4
	VMOVUPS.Z 64(R12), K2, Z5
	ADDQ DX, R12
	CMPQ R8, $3
	JLE  loop
	VMOVUPS.Z (R12), K1, Z6
	VMOVUPS.Z 64(R12), K2, Z7
	ADDQ DX, R12
	CMPQ R8, $4
	JLE  loop
	VMOVUPS.Z (R12), K1, Z8
	VMOVUPS.Z 64(R12), K2, Z9
	ADDQ DX, R12
	CMPQ R8, $5
	JLE  loop
	VMOVUPS.Z (R12), K1, Z10
	VMOVUPS.Z 64(R12), K2, Z11
	ADDQ DX, R12
	CMPQ R8, $6
	JLE  loop
	VMOVUPS.Z (R12), K1, Z12
	VMOVUPS.Z 64(R12), K2, Z13
	ADDQ DX, R12
	CMPQ R8, $7
	JLE  loop
	VMOVUPS.Z (R12), K1, Z14
	VMOVUPS.Z 64(R12), K2, Z15
	ADDQ DX, R12
	CMPQ R8, $8
	JLE  loop
	VMOVUPS.Z (R12), K1, Z16
	VMOVUPS.Z 64(R12), K2, Z17
	ADDQ DX, R12
	CMPQ R8, $9
	JLE  loop
	VMOVUPS.Z (R12), K1, Z18
	VMOVUPS.Z 64(R12), K2, Z19
	ADDQ DX, R12
	CMPQ R8, $10
	JLE  loop
	VMOVUPS.Z (R12), K1, Z20
	VMOVUPS.Z 64(R12), K2, Z21
	ADDQ DX, R12
	CMPQ R8, $11
	JLE  loop
	VMOVUPS.Z (R12), K1, Z22
	VMOVUPS.Z 64(R12), K2, Z23
	ADDQ DX, R12

loop:
	TESTQ CX, CX
	JZ    tail
	VMOVUPS.Z (SI), K1, Z24
	VMOVUPS.Z 64(SI), K2, Z25
	VFMADD231PS.BCST 0(AX), Z24, Z0
	VFMADD231PS.BCST 0(AX), Z25, Z1
	VFMADD231PS.BCST 4(AX), Z24, Z2
	VFMADD231PS.BCST 4(AX), Z25, Z3
	VFMADD231PS.BCST 8(AX), Z24, Z4
	VFMADD231PS.BCST 8(AX), Z25, Z5
	VFMADD231PS.BCST 12(AX), Z24, Z6
	VFMADD231PS.BCST 12(AX), Z25, Z7
	VFMADD231PS.BCST 16(AX), Z24, Z8
	VFMADD231PS.BCST 16(AX), Z25, Z9
	VFMADD231PS.BCST 20(AX), Z24, Z10
	VFMADD231PS.BCST 20(AX), Z25, Z11
	VFMADD231PS.BCST 24(AX), Z24, Z12
	VFMADD231PS.BCST 24(AX), Z25, Z13
	VFMADD231PS.BCST 28(AX), Z24, Z14
	VFMADD231PS.BCST 28(AX), Z25, Z15
	VFMADD231PS.BCST 32(AX), Z24, Z16
	VFMADD231PS.BCST 32(AX), Z25, Z17
	VFMADD231PS.BCST 36(AX), Z24, Z18
	VFMADD231PS.BCST 36(AX), Z25, Z19
	VFMADD231PS.BCST 40(AX), Z24, Z20
	VFMADD231PS.BCST 40(AX), Z25, Z21
	VFMADD231PS.BCST 44(AX), Z24, Z22
	VFMADD231PS.BCST 44(AX), Z25, Z23
	ADDQ $48, AX
	ADDQ BX, SI
	DECQ CX
	JMP  loop

tail:
	TESTQ R11, R11
	JZ    store
	VBROADCASTSS 0(R11), Z26
	VADDPS Z26, Z0, Z0
	VADDPS Z26, Z1, Z1
	VBROADCASTSS 4(R11), Z26
	VADDPS Z26, Z2, Z2
	VADDPS Z26, Z3, Z3
	VBROADCASTSS 8(R11), Z26
	VADDPS Z26, Z4, Z4
	VADDPS Z26, Z5, Z5
	VBROADCASTSS 12(R11), Z26
	VADDPS Z26, Z6, Z6
	VADDPS Z26, Z7, Z7
	VBROADCASTSS 16(R11), Z26
	VADDPS Z26, Z8, Z8
	VADDPS Z26, Z9, Z9
	VBROADCASTSS 20(R11), Z26
	VADDPS Z26, Z10, Z10
	VADDPS Z26, Z11, Z11
	VBROADCASTSS 24(R11), Z26
	VADDPS Z26, Z12, Z12
	VADDPS Z26, Z13, Z13
	VBROADCASTSS 28(R11), Z26
	VADDPS Z26, Z14, Z14
	VADDPS Z26, Z15, Z15
	VBROADCASTSS 32(R11), Z26
	VADDPS Z26, Z16, Z16
	VADDPS Z26, Z17, Z17
	VBROADCASTSS 36(R11), Z26
	VADDPS Z26, Z18, Z18
	VADDPS Z26, Z19, Z19
	VBROADCASTSS 40(R11), Z26
	VADDPS Z26, Z20, Z20
	VADDPS Z26, Z21, Z21
	VBROADCASTSS 44(R11), Z26
	VADDPS Z26, Z22, Z22
	VADDPS Z26, Z23, Z23

store:
	CMPQ R8, $0
	JLE  done
	VMOVUPS Z0, K1, (DI)
	VMOVUPS Z1, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $1
	JLE  done
	VMOVUPS Z2, K1, (DI)
	VMOVUPS Z3, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $2
	JLE  done
	VMOVUPS Z4, K1, (DI)
	VMOVUPS Z5, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $3
	JLE  done
	VMOVUPS Z6, K1, (DI)
	VMOVUPS Z7, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $4
	JLE  done
	VMOVUPS Z8, K1, (DI)
	VMOVUPS Z9, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $5
	JLE  done
	VMOVUPS Z10, K1, (DI)
	VMOVUPS Z11, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $6
	JLE  done
	VMOVUPS Z12, K1, (DI)
	VMOVUPS Z13, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $7
	JLE  done
	VMOVUPS Z14, K1, (DI)
	VMOVUPS Z15, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $8
	JLE  done
	VMOVUPS Z16, K1, (DI)
	VMOVUPS Z17, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $9
	JLE  done
	VMOVUPS Z18, K1, (DI)
	VMOVUPS Z19, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $10
	JLE  done
	VMOVUPS Z20, K1, (DI)
	VMOVUPS Z21, K2, 64(DI)
	ADDQ DX, DI
	CMPQ R8, $11
	JLE  done
	VMOVUPS Z22, K1, (DI)
	VMOVUPS Z23, K2, 64(DI)
	ADDQ DX, DI

done:
	VZEROUPPER
	RET
