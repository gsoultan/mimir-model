// func sgemm12x32w(a, b *float32, boff *int, c *float32, ldc, k, rows int, mask uint32, acc int, bias *float32)
//
// sgemm12x32 for the products of convolutions: row kk of B is at b +
// 4*boff[kk] rather than b + 4*kk*ldb, so the rows may be any windows of
// one array, such as the receptive fields in a padded image; and mask
// names the columns wanted, which each row of C holds packed together
// (a compress store, and an expand load with acc != 0), so that the
// positions past the end of an output row are dropped as they are made.
// Rows past rows are not computed.
