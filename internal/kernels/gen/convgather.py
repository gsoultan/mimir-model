# Generates convGatherF32: a convolution's outputs sixteen positions at a time,
# each tap's inputs gathered, for up to eight filters at once.
out = []
out.append("""// func convGatherF32(x *float32, idx *int32, masks *uint16, chunks, k int, w *float32, ws, rows int, bias *float32, y *float32, plane, tail int)
//
// For chunk c of 16 output positions and filter f < rows: y[f*plane +
// c*16 + j] = bias[f] + the sum over the taps t < k of w[t*ws+f] *
// x[idx[(c*k+t)*16+j]], the sum accumulated by fused multiply-adds in
// the taps' order as sgemm12x32 does, and bias added last (none when
// nil). Lanes clear in masks[c*k+t] read 0 instead of x. The last chunk
// stores the lanes of tail. Generated by gen/convgather.py.
TEXT ·convGatherF32(SB), NOSPLIT, $0-96
	MOVQ x+0(FP), SI
	MOVQ idx+8(FP), DX
	MOVQ masks+16(FP), R9
	MOVQ chunks+24(FP), R12
	MOVQ k+32(FP), R13
	MOVQ w+40(FP), R14
	MOVQ ws+48(FP), R15
	SHLQ $2, R15
	MOVQ rows+56(FP), AX
	MOVQ bias+64(FP), R10
	MOVQ y+72(FP), DI
	MOVQ plane+80(FP), R11
	SHLQ $2, R11
	MOVQ tail+88(FP), BX

cgchunk:
	TESTQ R12, R12
	JZ   cgdone
	KXNORW K2, K2, K2
	CMPQ R12, $1
	JNE  cgfull
	KMOVW BX, K2

cgfull:
""")
for f in range(8):
    out.append(f"\tVPXORD Z{f}, Z{f}, Z{f}\n")
out.append("\tMOVQ R14, R8\n\tMOVQ R13, CX\n")
for r in range(1, 9):
    out.append(f"\tCMPQ AX, ${r}\n\tJEQ  cg{r}taps\n")
out.append("\tJMP  cg8taps\n\n")
for r in range(1, 9):
    out.append(f"cg{r}taps:\n\tKMOVW (R9), K1\n\tVMOVDQU32 (DX), Z9\n\tVPXORD Z8, Z8, Z8\n\tVGATHERDPS (SI)(Z9*4), K1, Z8\n")
    for f in range(r):
        out.append(f"\tVFMADD231PS.BCST {4*f}(R8), Z8, Z{f}\n")
    out.append(f"\tADDQ R15, R8\n\tADDQ $64, DX\n\tADDQ $2, R9\n\tDECQ CX\n\tJNZ  cg{r}taps\n\tTESTQ R10, R10\n\tJZ   cg{r}store\n")
    for f in range(r):
        out.append(f"\tVADDPS.BCST {4*f}(R10), Z{f}, Z{f}\n")
    out.append(f"\ncg{r}store:\n\tMOVQ DI, R8\n")
    for f in range(r):
        out.append(f"\tVMOVUPS Z{f}, K2, (R8)\n")
        if f < r - 1:
            out.append("\tADDQ R11, R8\n")
    out.append("\tJMP  cgnext\n\n")
out.append("""cgnext:
	ADDQ $64, DI
	DECQ R12
	JMP  cgchunk

cgdone:
	VZEROUPPER
	RET

""")
print("".join(out), end="")
