// AMX kernels for 8-bit activations in blocks of 256 (amx.go). The tile
// instructions are written as bytes, since the Go assembler does not know
// them; each follows a comment with its mnemonic. A call loads its own
// tile configuration and releases the tiles before it returns: a goroutine
// may move to another thread between calls, and the Go scheduler does not
// save tile registers.
//
// For each block of 16 weight rows, each quant q is decoded with its
// sub-block scale sc to the integer w = q*sc for Q4_K, at most 945, and
// w = (q-32)*sc for Q6_K, within +-4096, and w is split into two bytes,
// w = lo + 256*hi. Two tile products over the whole block, of the lo and of
// the hi bytes with the activation quants, then give the block's integer
// sum S = sum w*y = lo + 256*hi for 16 weight rows by a group of 16
// activation rows, exactly as the one-row kernels compute it. Two groups
// share each load of the weights: tiles 0 and 1 hold the products of the
// first, 6 and 7 of the second, 2 and 3 the lo and hi bytes of 64 weights
// of the 16 rows, 4 and 5 the quants of the two groups for those 64, four
// per tile row and activation row. Every tile is 16 rows of 64 bytes.
//
// The scratch space at R14 (tileScratch in amx.go) holds the lo bytes at
// 0, a tile per 64 weights; the hi bytes at 4096; the four stored
// products at 8192; the Q4_K offsets as int16 pairs at 12288; d at 12544,
// dmin at 12608; the scales of the current Q4_K row, times 16, at 12672;
// the tile configuration at 12736.
//
// The arguments (tileArgs in amx.go), at a: w 0, wstride 8, nb 16,
// groups 24, act 32, gstride 40, xs 48, xsg 56, dx 64, dxg 72, tot 80,
// off 88, scr 96. The frame holds a at 0(SP), the blocks left at 8, the
// groups left at 16, and the current block's activations at 24, sums at
// 32, scales at 40 and weights at 48.

#define BYTES0F(reg) \
	VPCMPEQW  reg, reg, reg; \
	VPSRLW    $12, reg, reg; \
	VPACKUSWB reg, reg, reg

#define F16FINITE(mem, bad) \
	MOVWLZX mem, AX; \
	ANDL    $0x7C00, AX; \
	CMPL    AX, $0x7C00; \
	JEQ     bad

#define F16SCALAR(mem, xreg) \
	MOVWLZX   mem, AX; \
	VMOVD     AX, xreg; \
	VCVTPH2PS xreg, xreg

// Q4KSCALES unpacks the 6-bit scales and offsets of the Q4_K block at SI,
// as in kernels_amd64.s: the offsets m 0..7 as bytes in AX, the scales in
// R8. It uses BX.
#define Q4KSCALES \
	MOVL 12(SI), AX; \
	SHRL $4, AX; \
	ANDL $0x0f0f0f0f, AX; \
	MOVL 8(SI), BX; \
	SHRL $6, BX; \
	ANDL $0x03030303, BX; \
	SHLL $4, BX; \
	ORL  BX, AX; \
	MOVL 8(SI), BX; \
	ANDL $0x3f3f3f3f, BX; \
	SHLQ $32, AX; \
	ORQ  BX, AX; \
	MOVL 12(SI), R8; \
	ANDL $0x0f0f0f0f, R8; \
	MOVL 4(SI), BX; \
	SHRL $6, BX; \
	ANDL $0x03030303, BX; \
	SHLL $4, BX; \
	ORL  BX, R8; \
	MOVL 4(SI), BX; \
	ANDL $0x3f3f3f3f, BX; \
	SHLQ $32, R8; \
	ORQ  BX, R8

