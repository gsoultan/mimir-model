	VCVTDQ2PS    Z11, Z11
	VMULPS.BCST  24(CX), Z12, Z16
	VMOVUPS      192(R12), Z17
	VFMADD231PS  Z16, Z11, Z17
	VMOVUPS      Z17, 192(R12)
	VCVTDQ2PS    Z25, Z25
	VMULPS.BCST  28(CX), Z12, Z16
	VMOVUPS      192(R13), Z17
	VFMADD231PS  Z16, Z25, Z17
	VMOVUPS      Z17, 192(R13)

	ADDQ 40(DI), R9
	ADDQ 56(DI), R10
	ADDQ 72(DI), R11
	ADDQ $1024, R12
	ADDQ $1024, R13
	DECQ 16(SP)
	JNZ  q4g

	INCQ 8(SP)
	CMPQ 8(SP), $4
	JL   q4q
	INCQ 0(SP)
	MOVQ 0(SP), AX
	CMPQ AX, 16(DI)
	JL   q4b
	VZEROUPPER
	RET

