	VMOVDQU 48(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 832(R8)
	VMOVDQU Y0, 864(R8)
	VMOVDQU 80(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 896(R8)
	VMOVDQU Y0, 928(R8)
	VMOVDQU 112(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 960(R8)
	VMOVDQU Y0, 992(R8)
	// bq = 16*b + 4*q indexes the scales, offsets and d of the four rows.
	MOVQ 0(SP), AX
	SHLQ $4, AX
	MOVQ 8(SP), R14
	SHLQ $2, R14
	ADDQ R14, AX
	MOVQ AX, BX
	SHLQ $5, BX
	ADDQ 96(DI), BX
	MOVQ AX, DX
	SHLQ $4, DX
	ADDQ 104(DI), DX
	MOVQ AX, CX
	SHLQ $3, CX
	ADDQ 112(DI), CX
	MOVQ 0(SP), AX
	MOVQ AX, R9
	SHLQ $12, R9
	ADDQ 32(DI), R9
	MOVQ AX, R10
	SHLQ $8, R10
	ADDQ 48(DI), R10
	MOVQ AX, R11
	SHLQ $6, R11
	ADDQ 64(DI), R11
	MOVQ 8(SP), AX
	SHLQ $8, AX
	MOVQ AX, R12
	ADDQ 80(DI), R12
	MOVQ AX, R13
	ADDQ 88(DI), R13
	MOVQ 24(DI), AX
	MOVQ AX, 16(SP)

q4g:
	VPXORD Z8, Z8, Z8
	VPXORD Z9, Z9, Z9
	VPXORD Z10, Z10, Z10
	VPXORD Z11, Z11, Z11
	MOVQ   R9, R14
	XORQ   AX, AX

q4chunk:
	VPXORD Z0, Z0, Z0
	VPXORD Z1, Z1, Z1
	VPXORD Z2, Z2, Z2
	VPXORD Z3, Z3, Z3
	VPXORD Z4, Z4, Z4
	VPXORD Z5, Z5, Z5
	VPXORD Z6, Z6, Z6
	VPXORD Z7, Z7, Z7

q4t:
	VMOVDQU32 (R14), Z12    // four quants of sub-block 2c
	VMOVDQU32 512(R14), Z13 // and of 2c+1
	VPBROADCASTD 0(R8)(AX*1), Z14
	VPDPBUSD     Z12, Z14, Z0
	VPBROADCASTD 32(R8)(AX*1), Z15
	VPDPBUSD     Z13, Z15, Z1
	VPBROADCASTD 256(R8)(AX*1), Z16
	VPDPBUSD     Z12, Z16, Z2
	VPBROADCASTD 288(R8)(AX*1), Z17
	VPDPBUSD     Z13, Z17, Z3
	VPBROADCASTD 512(R8)(AX*1), Z18
	VPDPBUSD     Z12, Z18, Z4
	VPBROADCASTD 544(R8)(AX*1), Z19
	VPDPBUSD     Z13, Z19, Z5
	VPBROADCASTD 768(R8)(AX*1), Z20
	VPDPBUSD     Z12, Z20, Z6
	VPBROADCASTD 800(R8)(AX*1), Z21
	VPDPBUSD     Z13, Z21, Z7
	ADDQ  $64, R14
	ADDQ  $4, AX
	TESTQ $31, AX
	JNZ   q4t

	VPMULLD.BCST 0(BX), Z0, Z0
	VPMULLD.BCST 4(BX), Z1, Z1
	VPADDD       Z0, Z8, Z8
	VPADDD       Z1, Z8, Z8
	VPMULLD.BCST 32(BX), Z2, Z2
	VPMULLD.BCST 36(BX), Z3, Z3
	VPADDD       Z2, Z9, Z9
	VPADDD       Z3, Z9, Z9
	VPMULLD.BCST 64(BX), Z4, Z4
	VPMULLD.BCST 68(BX), Z5, Z5
	VPADDD       Z4, Z10, Z10
	VPADDD       Z5, Z10, Z10
	VPMULLD.BCST 96(BX), Z6, Z6
	VPMULLD.BCST 100(BX), Z7, Z7
	VPADDD       Z6, Z11, Z11
	VPADDD       Z7, Z11, Z11
	ADDQ $8, BX
	ADDQ $512, R14
	ADDQ $32, AX
	CMPQ AX, $256
	JL   q4chunk
	SUBQ $32, BX

	// M = sum of the offsets times the sums of 32 quants, by pairs.
	VMOVDQU32 (R10), Z12
	VMOVDQU32 64(R10), Z13
	VMOVDQU32 128(R10), Z14
	VMOVDQU32 192(R10), Z15
	VPBROADCASTD 0(DX), Z16
	VPMADDWD     Z16, Z12, Z22
	VPBROADCASTD 4(DX), Z16
	VPMADDWD     Z16, Z13, Z17
	VPADDD       Z17, Z22, Z22
	VPBROADCASTD 8(DX), Z16
	VPMADDWD     Z16, Z14, Z17
	VPADDD       Z17, Z22, Z22
	VPBROADCASTD 12(DX), Z16
	VPMADDWD     Z16, Z15, Z17
	VPADDD       Z17, Z22, Z22
	VPBROADCASTD 16(DX), Z16
	VPMADDWD     Z16, Z12, Z23
	VPBROADCASTD 20(DX), Z16
	VPMADDWD     Z16, Z13, Z17
	VPADDD       Z17, Z23, Z23
	VPBROADCASTD 24(DX), Z16
	VPMADDWD     Z16, Z14, Z17
	VPADDD       Z17, Z23, Z23
	VPBROADCASTD 28(DX), Z16
	VPMADDWD     Z16, Z15, Z17
	VPADDD       Z17, Z23, Z23
	VPBROADCASTD 32(DX), Z16
	VPMADDWD     Z16, Z12, Z24
	VPBROADCASTD 36(DX), Z16
	VPMADDWD     Z16, Z13, Z17
	VPADDD       Z17, Z24, Z24
	VPBROADCASTD 40(DX), Z16
	VPMADDWD     Z16, Z14, Z17
	VPADDD       Z17, Z24, Z24
	VPBROADCASTD 44(DX), Z16
	VPMADDWD     Z16, Z15, Z17
	VPADDD       Z17, Z24, Z24
	VPBROADCASTD 48(DX), Z16
	VPMADDWD     Z16, Z12, Z25
	VPBROADCASTD 52(DX), Z16
	VPMADDWD     Z16, Z13, Z17
	VPADDD       Z17, Z25, Z25
	VPBROADCASTD 56(DX), Z16
	VPMADDWD     Z16, Z14, Z17
	VPADDD       Z17, Z25, Z25
	VPBROADCASTD 60(DX), Z16
	VPMADDWD     Z16, Z15, Z17
	VPADDD       Z17, Z25, Z25

	VMOVUPS (R11), Z12 // dx
	VCVTDQ2PS    Z8, Z8
	VMULPS.BCST  0(CX), Z12, Z16
	VMOVUPS      0(R12), Z17
	VFMADD231PS  Z16, Z8, Z17
	VMOVUPS      Z17, 0(R12)
	VCVTDQ2PS    Z22, Z22
	VMULPS.BCST  4(CX), Z12, Z16
	VMOVUPS      0(R13), Z17
	VFMADD231PS  Z16, Z22, Z17
	VMOVUPS      Z17, 0(R13)
	VCVTDQ2PS    Z9, Z9
	VMULPS.BCST  8(CX), Z12, Z16
	VMOVUPS      64(R12), Z17
	VFMADD231PS  Z16, Z9, Z17
	VMOVUPS      Z17, 64(R12)
	VCVTDQ2PS    Z23, Z23
	VMULPS.BCST  12(CX), Z12, Z16
	VMOVUPS      64(R13), Z17
	VFMADD231PS  Z16, Z23, Z17
	VMOVUPS      Z17, 64(R13)
	VCVTDQ2PS    Z10, Z10
	VMULPS.BCST  16(CX), Z12, Z16
	VMOVUPS      128(R12), Z17
	VFMADD231PS  Z16, Z10, Z17
