// AVX-512 VNNI kernels for 8-bit activations in blocks of 256 (vnni.go).
//
// For each block of each run of four weight rows, the quants of the four
// rows are first written to the scratch space at R8, one byte each in the
// order of the elements, 256 bytes per row. Then, for each group of 16
// activation rows, whose quants come four elements per row, 64 bytes per
// four elements (TileActs.q), VPDPBUSD multiplies four quants of a weight
// row, broadcast to the 16 lanes, by the four quants of each activation
// row, and adds the four products into the lane's int32 sum. Two
// sub-blocks of the four rows go side by side, eight sums in Z0..Z7, and
// each is scaled by its sub-block scale in int32 and added to the row's
// block sum S in Z8..Z11. The block's float32 work is then that of the
// one-row kernels, in each lane: tot += float32(S) * (d*dx), and for Q4_K
// off += float32(M) * (dmin*dx).
//
// The arguments (vnniArgs in vnni.go), at DI: w 0, wstride 8, nb 16,
// groups 24, act 32, gstride 40, xs 48, xsg 56, dx 64, dxg 72, tot 80,
// off 88, sc 96, mp 104, dd 112, scr 120. The frame holds the block at
// 0(SP), the run of four rows at 8 and the groups left at 16. In the loop
// over groups, R9 points at the group's quants for the block, R10 at its
// sums, R11 at its scales, R12 and R13 at the totals and offsets of the
// first of the four rows, BX at the rows' sub-block scales, DX at their
// Q4_K offsets and CX at their d and dmin.

DATA nib0f<>+0(SB)/8, $0x0f0f0f0f0f0f0f0f
DATA nib0f<>+8(SB)/8, $0x0f0f0f0f0f0f0f0f
DATA nib0f<>+16(SB)/8, $0x0f0f0f0f0f0f0f0f
DATA nib0f<>+24(SB)/8, $0x0f0f0f0f0f0f0f0f
GLOBL nib0f<>(SB), RODATA|NOPTR, $32

DATA bits30<>+0(SB)/8, $0x3030303030303030
DATA bits30<>+8(SB)/8, $0x3030303030303030
DATA bits30<>+16(SB)/8, $0x3030303030303030
DATA bits30<>+24(SB)/8, $0x3030303030303030
GLOBL bits30<>(SB), RODATA|NOPTR, $32

// func vnniQ4K(a *vnniArgs)
