	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 192(R8)
	VMOVDQU Y0, 224(R8)
	LEAQ    (SI)(AX*1), R14
	VMOVDQU 16(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
