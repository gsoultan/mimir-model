	IMULQ   $144, AX
	MOVQ    8(SP), SI
	SHLQ    $2, SI
	IMULQ   8(DI), SI
	ADDQ    AX, SI
	ADDQ    0(DI), SI
	MOVQ    120(DI), R8
	MOVQ    8(DI), AX
	VMOVDQU nib0f<>(SB), Y15
	VMOVDQU 16(SI), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 0(R8)
