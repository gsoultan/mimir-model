	VMOVDQU 48(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 320(R8)
	VMOVDQU Y0, 352(R8)
	VMOVDQU 80(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 384(R8)
	VMOVDQU Y0, 416(R8)
	VMOVDQU 112(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 448(R8)
	VMOVDQU Y0, 480(R8)
	LEAQ    (SI)(AX*2), R14
	VMOVDQU 16(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 512(R8)
	VMOVDQU Y0, 544(R8)
	VMOVDQU 48(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 576(R8)
