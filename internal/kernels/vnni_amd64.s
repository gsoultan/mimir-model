	VMOVDQU 112(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 704(R8)
	VMOVDQU Y0, 736(R8)
	ADDQ    AX, R14
	VMOVDQU 16(R14), Y0
	VPAND   Y15, Y0, Y1
	VPSRLW  $4, Y0, Y0
	VPAND   Y15, Y0, Y0
	VMOVDQU Y1, 768(R8)
