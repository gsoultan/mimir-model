p4max:
	VCMPPS $0, Z1, Z0, K4
	VMAXPS Z0, Z1, Z2
	VANDPS Z1, Z0, K4, Z2
	VCMPPS $3, Z1, Z1, K4
	VMOVAPS Z31, K4, Z2
	VMOVAPS Z2, Z0
	VCMPPS $0, Z5, Z4, K4
	VMAXPS Z4, Z5, Z6
	VANDPS Z5, Z4, K4, Z6
	VCMPPS $3, Z5, Z5, K4
	VMOVAPS Z31, K4, Z6
	VMOVAPS Z6, Z4
	VCMPPS $0, Z9, Z8, K4
	VMAXPS Z8, Z9, Z10
	VANDPS Z9, Z8, K4, Z10
	VCMPPS $3, Z9, Z9, K4
	VMOVAPS Z31, K4, Z10
	VMOVAPS Z10, Z8
	VCMPPS $0, Z13, Z12, K4
	VMAXPS Z12, Z13, Z14
	VANDPS Z13, Z12, K4, Z14
	VCMPPS $3, Z13, Z13, K4
	VMOVAPS Z31, K4, Z14
	VMOVAPS Z14, Z12

p4next:
	ADDQ $8, R8
	DECQ R15
	JNZ  p4tap
	// With taps combined, any NaN is the canonical one.
	CMPQ R14, $1
	JEQ  p4store
	VCMPPS $3, Z0, Z0, K4
	VMOVAPS Z31, K4, Z0
	VCMPPS $3, Z4, Z4, K4
	VMOVAPS Z31, K4, Z4
	VCMPPS $3, Z8, Z8, K4
	VMOVAPS Z31, K4, Z8
	VCMPPS $3, Z12, Z12, K4
	VMOVAPS Z31, K4, Z12

p4store:
	MOVQ yrs4-40(SP), R10
	MOVQ DI, R8
	VMOVUPS Z0, K1, (R8)
	ADDQ R10, R8
	VMOVUPS Z4, K1, (R8)
	ADDQ R10, R8
	VMOVUPS Z8, K1, (R8)
	ADDQ R10, R8
	VMOVUPS Z12, K1, (R8)
	ADDQ $64, DI
	ADDQ xchunk-48(SP), SI
	SUBQ $16, CX
	JMP  p4loop

p4rowend:
	// y and x moved on by the row's chunks of 16: y back to the row's
	// end and on to the next row, x back to the row's start and on by
	// the rows done.
	MOVQ R11, CX
	ANDQ $15, CX
	JZ   p4rows
	SUBQ $64, DI
	LEAQ (DI)(CX*4), DI

p4rows:
	ADDQ ynext-56(SP), DI
	SUBQ xback-64(SP), SI
	ADDQ yrs4-40(SP), DI
	ADDQ R13, SI
	ADDQ yrs4-40(SP), DI
	ADDQ R13, SI
	ADDQ yrs4-40(SP), DI
	ADDQ R13, SI
	ADDQ R13, SI
	SUBQ $4, R12
	JMP  poolrows

