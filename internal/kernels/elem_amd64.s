// AVX-512 kernel for element-wise float32 operations (elem.go).

// func binF32(op int, y, x, z *float32, n, scalar int, nan float32)
//
// y[j] = x[j] op z[j] (z[0] when scalar != 0) for j < n, op 0 add, 1
// multiply, 2 maximum. An add or multiply whose result is NaN gives nan.
// The maximum is nan when either operand is NaN; when the operands are
// equal (including +0 and -0) it is their bitwise and, which is either
// of them for equal nonzero values, -0 for two -0 and +0 otherwise;
// otherwise the larger.
TEXT ·binF32(SB), NOSPLIT, $0-52
	MOVQ op+0(FP), AX
	MOVQ y+8(FP), DI
	MOVQ x+16(FP), SI
	MOVQ z+24(FP), DX
	MOVQ n+32(FP), CX
	MOVQ scalar+40(FP), BX
	VBROADCASTSS nan+48(FP), Z31
	VBROADCASTSS (DX), Z30
	MOVQ $16, R9
	TESTQ BX, BX
	JZ   stride
	XORQ R9, R9 // z does not advance
stride:
	SHLQ $2, R9
	KXNORW K1, K1, K1 // all 16 lanes

loop:
	CMPQ CX, $16
	JGE  body
	TESTQ CX, CX
	JZ   done
	// The last n < 16 floats: lanes below n.
	MOVL $1, R8
	SHLL CX, R8
	DECL R8
	KMOVW R8, K1
	MOVQ $16, CX

body:
	VMOVUPS.Z (SI), K1, Z0
	VMOVAPS  Z30, Z1
	TESTQ BX, BX
	JNZ  op
	VMOVUPS.Z (DX), K1, Z1

op:
	CMPQ AX, $1
	JEQ  mul
	JGT  max
	VADDPS Z1, Z0, Z2
	JMP  fixnan

mul:
	VMULPS Z1, Z0, Z2

fixnan:
	VCMPPS $3, Z2, Z2, K2 // unordered: the result is NaN
	VMOVAPS Z31, K2, Z2
	JMP  store

max:
	VMAXPS Z1, Z0, Z2
	VCMPPS $0, Z1, Z0, K2 // equal
	VANDPS Z1, Z0, K2, Z2
	VCMPPS $3, Z1, Z0, K2 // either is NaN
	VMOVAPS Z31, K2, Z2

store:
	VMOVUPS Z2, K1, (DI)
	ADDQ $64, SI
	ADDQ $64, DI
	ADDQ R9, DX
	SUBQ $16, CX
	JMP  loop

done:
	VZEROUPPER
	RET

// func poolF32(op int, y, x *float32, offs *int, taps, w, rows, stride, xrs, yrs int, nan float32)
//
// rows rows of w outputs, y[r*yrs+j] = the op over the taps t of
// x[offs[t]+r*xrs+j*stride], op as for binF32 and applied in order.
// stride is 1 or 2. Rows go four at a time while there are four, each
// in its own accumulator, so the taps of one row need not wait on each
// other; rows of at most 8 outputs go two to a vector, eight at a time
// while there are eight. Generated by gen/pool.py.
TEXT ·poolF32(SB), NOSPLIT, $64-84
	MOVQ op+0(FP), AX
	MOVQ y+8(FP), DI
	MOVQ x+16(FP), SI
	MOVQ offs+24(FP), R9
	MOVQ taps+32(FP), R14
	MOVQ w+40(FP), R11
	MOVQ rows+48(FP), R12
	MOVQ stride+56(FP), BX
	MOVQ xrs+64(FP), R13
	SHLQ $2, R13
	VBROADCASTSS nan+80(FP), Z31
	VMOVDQU32 evens<>(SB), Z30
	// The lanes of a row's last chunk: of y, and of the two source loads
	// of stride 2, the last even lane and below.
	MOVQ R11, CX
	ANDQ $15, CX
	MOVL $1, R8
	SHLL CX, R8
	DECL R8
	MOVQ R8, ytail-24(SP)
	MOVL $1, R8
	SHLL CX, R8
	SHLL CX, R8
	SHRL $1, R8
	DECL R8
	MOVL R8, R10
	ANDL $0xffff, R10
	MOVQ R10, xtail-16(SP)
	SHRL $16, R8
	MOVQ R8, xtail2-8(SP)
	MOVQ $0x7fff, R8 // a full chunk of stride 2: lanes 0 to 30
	MOVQ R8, full2-32(SP)
	// The row strides of y in bytes; from a row's end in y to the next
	// row's start; a chunk's source, 16 or 32 elements, and a row's.
	MOVQ yrs+72(FP), R8
	SHLQ $2, R8
	MOVQ R8, yrs4-40(SP)
	MOVQ yrs+72(FP), R8
	SUBQ R11, R8
	SHLQ $2, R8
	MOVQ R8, ynext-56(SP)
	MOVQ BX, R8
	SHLQ $6, R8
	MOVQ R8, xchunk-48(SP)
	MOVQ R11, R8
	ADDQ $15, R8
	ANDQ $-16, R8
	IMULQ BX, R8
	SHLQ $2, R8
	MOVQ R8, xback-64(SP)

poolrows:
	TESTQ R12, R12
	JZ   pooldone
	CMPQ R11, $8
	JG   poolwide
	CMPQ R12, $8
	JGE  q4chunks
	CMPQ R12, $2
	JGE  q1chunks
	JMP  p1chunks

poolwide:
	CMPQ R12, $4
	JGE  p4chunks
	JMP  p1chunks

p4chunks:
	MOVQ R11, CX // elements left in the row
	KXNORW K1, K1, K1
	KXNORW K2, K2, K2
	KMOVW full2-32(SP), K3

p4loop:
	CMPQ CX, $16
	JGE  p4body
	TESTQ CX, CX
	JZ   p4rowend
	KMOVW ytail-24(SP), K1
	KMOVW xtail-16(SP), K2
	KMOVW xtail2-8(SP), K3
	MOVQ $16, CX

p4body:
	MOVQ R9, R8
	MOVQ R14, R15

p4tap:
	MOVQ (R8), R10
	LEAQ (SI)(R10*4), DX
	CMPQ BX, $1
	JNE  p4even
	VMOVUPS.Z (DX), K1, Z1
	VMOVUPS.Z (DX)(R13*1), K1, Z5
	VMOVUPS.Z (DX)(R13*2), K1, Z9
	LEAQ (DX)(R13*2), R10
	VMOVUPS.Z (R10)(R13*1), K1, Z13
	JMP  p4loaded

p4even:
	VMOVUPS.Z (DX), K2, Z1
	VMOVUPS.Z 64(DX), K3, Z2
	VMOVDQA32 Z30, Z3
	VPERMI2PS Z2, Z1, Z3 // Z3 = the even lanes of Z1:Z2
	VMOVAPS Z3, Z1
	VMOVUPS.Z (DX)(R13*1), K2, Z5
	VMOVUPS.Z 64(DX)(R13*1), K3, Z6
	VMOVDQA32 Z30, Z7
	VPERMI2PS Z6, Z5, Z7 // Z7 = the even lanes of Z5:Z6
	VMOVAPS Z7, Z5
	VMOVUPS.Z (DX)(R13*2), K2, Z9
	VMOVUPS.Z 64(DX)(R13*2), K3, Z10
	VMOVDQA32 Z30, Z11
	VPERMI2PS Z10, Z9, Z11 // Z11 = the even lanes of Z9:Z10
	VMOVAPS Z11, Z9
	LEAQ (DX)(R13*2), R10
	VMOVUPS.Z (R10)(R13*1), K2, Z13
	VMOVUPS.Z 64(R10)(R13*1), K3, Z14
	VMOVDQA32 Z30, Z15
	VPERMI2PS Z14, Z13, Z15 // Z15 = the even lanes of Z13:Z14
	VMOVAPS Z15, Z13

p4loaded:
	CMPQ R15, R14
	JNE  p4acc
	VMOVAPS Z1, Z0
	VMOVAPS Z5, Z4
	VMOVAPS Z9, Z8
	VMOVAPS Z13, Z12
	JMP  p4next

p4acc:
	CMPQ AX, $1
	JEQ  p4mul
	JGT  p4max
	VADDPS Z1, Z0, Z0
	VADDPS Z5, Z4, Z4
