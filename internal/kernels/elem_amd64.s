	ADDQ yrs4-40(SP), DI
	ADDQ R13, SI
	ADDQ R13, SI
	SUBQ $2, R12
	JMP  poolrows

pooldone:
	VZEROUPPER
	RET

// func poolGatherF32(op int, y, x *float32, idx *int32, np, taps, n int, nan float32)
//
// y[j] = the op over the taps t of x[idx[t*np+j]] for j < n, op as for
// binF32 and applied in order. np is a multiple of 16 of at least n.
TEXT ·poolGatherF32(SB), NOSPLIT, $0-60
	MOVQ op+0(FP), AX
	MOVQ y+8(FP), DI
	MOVQ x+16(FP), SI
	MOVQ idx+24(FP), R9
	MOVQ np+32(FP), R13
	SHLQ $2, R13
	MOVQ taps+40(FP), R14
	MOVQ n+48(FP), CX
	VBROADCASTSS nan+56(FP), Z31
	KXNORW K1, K1, K1 // all 16 lanes

pgloop:
	CMPQ CX, $16
	JGE  pgbody
	TESTQ CX, CX
	JZ   pgdone
	// The last n < 16 outputs: lanes below n.
	MOVL $1, R8
	SHLL CX, R8
	DECL R8
	KMOVW R8, K1
	MOVQ $16, CX

pgbody:
	KXORW K5, K5, K5
	MOVQ R9, R8
	MOVQ R14, R15

pgtap:
	VMOVDQU32 (R8), Z3
	KMOVW K1, K2 // the gather uses up its mask
	VPXORD Z1, Z1, Z1
	VGATHERDPS (SI)(Z3*4), K2, Z1
	CMPQ R15, R14
	JNE  pgacc
	VMOVAPS Z1, Z0
	JMP  pgcnext

pgacc:
	CMPQ AX, $1
	JEQ  pgmul
	JGT  pgmax
	VADDPS Z1, Z0, Z0
	JMP  pgcnext

pgmul:
	VMULPS Z1, Z0, Z0
	JMP  pgcnext

pgmax:
	VCMPPS $3, Z1, Z0, K4 // either is NaN
	KORW K4, K5, K5
	VCMPPS $0, Z1, Z0, K4 // equal: and, for the sign of zero
	VMAXPS Z1, Z0, Z2
	VANDPS Z1, Z0, K4, Z2
	VMOVAPS Z2, Z0

pgcnext:
	ADDQ R13, R8
	DECQ R15
	JNZ  pgtap
	// Any NaN among the taps or made by them is the canonical one.
	VCMPPS $3, Z0, Z0, K4
	KORW K4, K5, K4
	VMOVAPS Z31, K4, Z0
	VMOVUPS Z0, K1, (DI)
	ADDQ $64, R9
	ADDQ $64, DI
	SUBQ $16, CX
	JMP  pgloop

pgdone:
	VZEROUPPER
	RET

// func rowsF32(op int, y, v *float32, rows, plane int, nan float32)
//
// y[r*plane+j] = y[r*plane+j] op v[r] for r < rows, j < plane, op as for
// binF32.
TEXT ·rowsF32(SB), NOSPLIT, $0-44
	MOVQ op+0(FP), AX
	MOVQ y+8(FP), DI
	MOVQ v+16(FP), SI
	MOVQ rows+24(FP), R12
	MOVQ plane+32(FP), R11
	VBROADCASTSS nan+40(FP), Z31

rwrows:
	TESTQ R12, R12
	JZ   rwdone
	VBROADCASTSS (SI), Z1
	MOVQ R11, CX
	KXNORW K1, K1, K1

rwloop:
	CMPQ CX, $16
	JGE  rwbody
	TESTQ CX, CX
	JZ   rwnext
	MOVL $1, R8
	SHLL CX, R8
	DECL R8
	KMOVW R8, K1
	MOVQ $16, CX

rwbody:
	VMOVUPS.Z (DI), K1, Z0
	CMPQ AX, $1
	JEQ  rwmul
	JGT  rwmax
	VADDPS Z1, Z0, Z2
	JMP  rwfixnan

rwmul:
	VMULPS Z1, Z0, Z2

rwfixnan:
	VCMPPS $3, Z2, Z2, K4 // unordered: the result is NaN
	VMOVAPS Z31, K4, Z2
	JMP  rwstore

rwmax:
	VMAXPS Z1, Z0, Z2
	VCMPPS $0, Z1, Z0, K4 // equal
	VANDPS Z1, Z0, K4, Z2
	VCMPPS $3, Z1, Z0, K4 // either is NaN
	VMOVAPS Z31, K4, Z2

rwstore:
	VMOVUPS Z2, K1, (DI)
	ADDQ $64, DI
	SUBQ $16, CX
	JMP  rwloop

rwnext:
	// y moved on by the row's chunks of 16; back to the row's end.
	MOVQ R11, CX
	ANDQ $15, CX
	JZ   rwrow
	SUBQ $64, DI
	LEAQ (DI)(CX*4), DI

rwrow:
	ADDQ $4, SI
	DECQ R12
	JMP  rwrows

rwdone:
	VZEROUPPER
	RET

// func epilogueF32(y *float32, rows, plane int, ops *int, steps int, v *float32, vs int, nan float32)
//
// For each row r < rows and step s < steps, in order: y[r*plane+j] =
// y[r*plane+j] ops[s] v[s*vs+r], op as for binF32, in one pass over y.
TEXT ·epilogueF32(SB), NOSPLIT, $0-60
	MOVQ y+0(FP), DI
	MOVQ rows+8(FP), R12
	MOVQ plane+16(FP), R11
	MOVQ ops+24(FP), R13
	MOVQ steps+32(FP), R14
	MOVQ v+40(FP), SI
	MOVQ vs+48(FP), R9
	SHLQ $2, R9
	VBROADCASTSS nan+56(FP), Z31

eprows:
	TESTQ R12, R12
	JZ   epdone
	MOVQ R11, CX
	KXNORW K1, K1, K1

eploop:
	CMPQ CX, $16
	JGE  epbody
	TESTQ CX, CX
	JZ   epnext
	MOVL $1, R8
	SHLL CX, R8
	DECL R8
	KMOVW R8, K1
	MOVQ $16, CX

epbody:
	VMOVUPS.Z (DI), K1, Z0
	KXORW K5, K5, K5 // the lanes that were NaN at some step
	MOVQ R13, R8
	MOVQ SI, R10 // this row's value of the step
	MOVQ R14, R15

epstep:
	MOVQ (R8), AX
	CMPQ AX, $1
	JEQ  epmul
	JGT  epmax
	VADDPS.BCST (R10), Z0, Z0
	JMP  epstepped

epmul:
	VMULPS.BCST (R10), Z0, Z0
	JMP  epstepped

epmax:
	VCMPPS $3, Z0, Z0, K4 // NaN, lost by max
	KORW K4, K5, K5
	VCMPPS.BCST $0, (R10), Z0, K4 // equal: and, for the sign of zero
	VMAXPS.BCST (R10), Z0, Z2
	VANDPS.BCST (R10), Z0, K4, Z2
	VMOVAPS Z2, Z0

epstepped:
	ADDQ $8, R8
	ADDQ R9, R10
	DECQ R15
	JNZ  epstep
	// A NaN at any step is the canonical one.
	VCMPPS $3, Z0, Z0, K4
	KORW K4, K5, K4
	VMOVAPS Z31, K4, Z0
	VMOVUPS Z0, K1, (DI)
	ADDQ $64, DI
	SUBQ $16, CX
	JMP  eploop

epnext:
	// y moved on by the row's chunks of 16; back to the row's end.
	MOVQ R11, CX
	ANDQ $15, CX
	JZ   eprow
	SUBQ $64, DI
	LEAQ (DI)(CX*4), DI

eprow:
	ADDQ $4, SI
	DECQ R12
	JMP  eprows

epdone:
	VZEROUPPER
	RET

// func padPlaneF32(y, x *float32, h, w, hp, wp, top, left int, v float32)
//
// y, hp rows of wp, is x, h rows of w, at row top, column left, and v
// everywhere else. left+w is at most 64.
TEXT ·padPlaneF32(SB), NOSPLIT, $0-68
	MOVQ y+0(FP), DI
	MOVQ x+8(FP), SI
	MOVQ h+16(FP), R12
	MOVQ w+24(FP), R11
	MOVQ hp+32(FP), R13
	MOVQ wp+40(FP), R14
	MOVQ top+48(FP), R10
	MOVQ left+56(FP), R9
	VBROADCASTSS v+64(FP), Z1
	// The columns of x in a padded row: bits left to left+w-1.
	MOVQ $1, BX
	MOVQ R11, CX
	SHLQ CX, BX
	DECQ BX
	MOVQ R9, CX
	SHLQ CX, BX
	// x moved back by left, so that column c of the padded row is at
	// element c of it.
	LEAQ (SI)(R9*4), SI
	MOVQ R9, CX
	SHLQ $3, CX
	SUBQ CX, SI
	XORQ DX, DX // the row; rows top to top+h-1 hold x

pprow:
	CMPQ DX, R13
	JGE  ppdone
	MOVQ R14, CX // columns left
	MOVQ BX, R15 // the x columns of the chunk
	SUBQ R10, DX
	CMPQ DX, R12 // unsigned: below h when the row holds x
	JB   ppx
	XORQ R15, R15

ppx:
	ADDQ R10, DX
	MOVQ DI, R8

ppchunk:
	TESTQ CX, CX
	JZ   ppnext
	MOVL $0xffff, AX
	CMPQ CX, $16
	JGE  ppfull
	MOVL $1, AX
	SHLL CX, AX
	DECL AX

ppfull:
	KMOVW AX, K1
	MOVQ R15, AX
	ANDL $0xffff, AX
	KMOVW AX, K2
	VMOVAPS Z1, Z0
	VMOVUPS (SI), K2, Z0 // x's columns, over v
	VMOVUPS Z0, K1, (R8)
	ADDQ $64, R8
	ADDQ $64, SI
	SHRQ $16, R15
	SUBQ $16, CX
	JGE  ppchunk

ppnext:
	// x back to the row's start and on by a row when this row held it;
	// y on by a row.
	MOVQ R14, CX
	ADDQ $15, CX
	ANDQ $-16, CX
	SHLQ $2, CX
	SUBQ CX, SI
	SUBQ R10, DX
	CMPQ DX, R12
	JAE  ppy
	LEAQ (SI)(R11*4), SI

ppy:
	ADDQ R10, DX
	LEAQ (DI)(R14*4), DI
	INCQ DX
	JMP  pprow

ppdone:
	VZEROUPPER
	RET

